  const pattern = new RegExp(Object.keys(ukrainian).sort((a, b) => b.length - a.length).map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
  let language = 'ru';
  try { if (localStorage.getItem('fartoviy-language') === 'uk') language = 'uk'; } catch { /* Use the default when storage is unavailable. */ }
  const text = (source, target = language) => target === 'uk' ? source.replace(pattern, match => ukrainian[match]) : source;
  const originals = new WeakMap();
  const attributes = new WeakMap();
  const translatedAttributes = ['aria-label', 'placeholder', 'title', 'alt'];

  function translateUI() {
    document.documentElement.lang = language;
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement.closest('script, style, noscript, [data-language]')) continue;
      let record = originals.get(node);
      if (!record || record.last !== node.data) record = { source: node.data, last: node.data };
      const translated = text(record.source);
      if (node.data !== translated) node.data = translated;
      record.last = translated;
      originals.set(node, record);
    }
    document.querySelectorAll('[aria-label], [placeholder], [title], [alt], meta[name="description"]').forEach(el => {
      let records = attributes.get(el);
      if (!records) { records = new Map(); attributes.set(el, records); }
      for (const name of el.matches('meta') ? ['content'] : translatedAttributes) {
        if (!el.hasAttribute(name)) continue;
        const value = el.getAttribute(name);
        let record = records.get(name);
        if (!record || record.last !== value) record = { source: value, last: value };
        const translated = text(record.source);
        if (value !== translated) el.setAttribute(name, translated);
        record.last = translated;
        records.set(name, record);
      }
    });
    document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
  }

  function setLanguage(next) {
    if (!['ru', 'uk'].includes(next)) return;
    language = next;
    try { localStorage.setItem('fartoviy-language', language); } catch { /* Switching still works for this visit. */ }
    translateUI();
  }

  window.FartoviyI18n = { text, setLanguage, translateUI, get language() { return language; } };
  document.addEventListener('click', event => {
    const button = event.target.closest('[data-language]');
    if (button) setLanguage(button.dataset.language);
  });
  document.addEventListener('DOMContentLoaded', () => {
    translateUI();
    // Dynamic routes, dialog messages, and toast updates use the same translations.
    const observer = new MutationObserver(translateUI);
    observer.observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes, 'content'] });
  });
